#!/usr/bin/env python3
"""Generates the SYNTHETIC sample photos for recipes-preview/recipes-photos.js (drawn shapes and the word SAMPLE; no real photographs).
Run from the repo root:  python3 tests/recipes/make-photos.py
Good samples respect the preview limits (800px longest edge, 150 KB). The 'bad' samples break exactly one rule each, on purpose."""
import base64, io, json, os, random
from PIL import Image, ImageDraw, ImageFont

def font(size):
    for p in ("/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf",):
        if os.path.exists(p): return ImageFont.truetype(p, size)
    return ImageFont.load_default()

def scene(w, h, c1, c2, shape):
    im = Image.new("RGB", (w, h), c1); d = ImageDraw.Draw(im)
    for y in range(h):
        t = y / max(1, h - 1); d.line([(0, y), (w, y)], fill=tuple(int(c1[i] + (c2[i] - c1[i]) * t) for i in range(3)))
    m = min(w, h)
    if shape == "bowl":
        d.ellipse([w*.2, h*.35, w*.8, h*.95], fill=(245, 245, 240)); d.ellipse([w*.25, h*.4, w*.75, h*.7], fill=(200, 60, 40))
    elif shape == "plate":
        d.ellipse([w*.15, h*.2, w*.85, h*.9], fill=(250, 250, 250)); d.ellipse([w*.3, h*.35, w*.7, h*.75], fill=(230, 190, 90))
    else:
        for i in range(5): d.ellipse([w*(.1+.17*i), h*.3+(i%2)*h*.2, w*(.1+.17*i)+m*.2, h*.3+(i%2)*h*.2+m*.2], fill=(214, 170, 110))
    f = font(max(14, m // 12)); d.text((w*.05, h*.04), "SAMPLE", fill=(255, 255, 255), font=f)
    return im

def enc(im, fmt, **kw):
    b = io.BytesIO(); im.save(b, fmt, **kw); return b.getvalue()

def url(mime, raw): return "data:%s;base64,%s" % (mime, base64.b64encode(raw).decode())

out = {}
def add(key, label, kind, mime, raw, note):
    out[key] = {"label": label, "kind": kind, "note": note, "dataUrl": url(mime, raw)}

add("bowl", "Red bowl (JPEG 640x427)", "good", "image/jpeg", enc(scene(640, 427, (250, 220, 170), (230, 150, 90), "bowl"), "JPEG", quality=80), "Fits the limits.")
add("plate", "Golden plate (PNG 600x400)", "good", "image/png", enc(scene(600, 400, (200, 220, 240), (120, 150, 200), "plate"), "PNG", optimize=True), "Fits the limits.")
add("cookies", "Cookies (JPEG 800x600)", "good", "image/jpeg", enc(scene(800, 600, (240, 230, 210), (200, 170, 130), "cookies"), "JPEG", quality=75), "Exactly 800px on the longest edge: allowed.")
add("tall", "Tall photo (JPEG 400x800)", "good", "image/jpeg", enc(scene(400, 800, (210, 240, 215), (90, 160, 110), "plate"), "JPEG", quality=75), "Portrait. Shown at its own proportions, never stretched.")
add("bad-wide", "Too wide (JPEG 1200x800)", "bad", "image/jpeg", enc(scene(1200, 800, (240, 200, 200), (180, 90, 90), "bowl"), "JPEG", quality=70), "Rejected: longest edge over 800px.")
random.seed(7); noise = Image.effect_noise((440, 440), 90).convert("RGB")
add("bad-heavy", "Too heavy (JPEG 440x440)", "bad", "image/jpeg", enc(noise, "JPEG", quality=95), "Rejected: file over 150 KB.")
gif = Image.new("P", (120, 120)); ImageDraw.Draw(gif).ellipse([10, 10, 110, 110], fill=1)
add("bad-gif", "Wrong type (GIF)", "bad", "image/gif", enc(gif, "GIF"), "Rejected: only JPEG and PNG are supported in this preview.")
svg = b'<svg xmlns="http://www.w3.org/2000/svg" width="100" height="100"><circle cx="50" cy="50" r="40" fill="orange"/></svg>'
add("bad-svg", "Wrong type (SVG)", "bad", "image/svg+xml", svg, "Rejected: SVG is never accepted as a photo.")
out["bad-external"] = {"label": "External link (themealdb.com)", "kind": "bad", "note": "Rejected: the preview never loads a picture from another website.", "dataUrl": "https://www.themealdb.com/images/media/meals/sample.jpg"}
out["bad-corrupt"] = {"label": "Unreadable (corrupt JPEG)", "kind": "bad", "note": "Rejected: the file header cannot be read.", "dataUrl": "data:image/jpeg;base64,/9j/4AAQSkZJRgABAQEASABIAAAAAAAAAA=="}

js = "/* GENERATED by tests/recipes/make-photos.py. SYNTHETIC drawings only (no real photographs). Do not edit by hand. */\n" \
     "(function (root) { var P = " + json.dumps(out, separators=(",", ":")) + ";\n" \
     "  if (typeof module === 'object' && module.exports) module.exports = P; else root.RecipesPhotos = P;\n" \
     "})(typeof self !== 'undefined' ? self : this);\n"
open("recipes-preview/recipes-photos.js", "w").write(js)
for k, v in out.items():
    if v["dataUrl"].startswith("data:"):
        print(k, len(base64.b64decode(v["dataUrl"].split(",", 1)[1])), "bytes")
